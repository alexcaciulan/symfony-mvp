<?php

declare(strict_types=1);

namespace App\Repository;

use App\Entity\CaseDraft;
use App\Entity\Document;
use App\Entity\LegalCase;
use App\Enum\DocumentType;
use App\Enum\ExtractionStatus;
use Doctrine\Bundle\DoctrineBundle\Repository\ServiceEntityRepository;
use Doctrine\Persistence\ManagerRegistry;

/** @extends ServiceEntityRepository<Document> */
class DocumentRepository extends ServiceEntityRepository
{
    public function __construct(ManagerRegistry $registry)
    {
        parent::__construct($registry, Document::class);
    }

    /**
     * Documents attached to a case, ordered newest first. Used by Tab Documente
     * on the case overview page (Pas 4.0.4) to render the source uploads list.
     *
     * @return Document[]
     */
    public function findByCase(LegalCase $case): array
    {
        return $this->createQueryBuilder('d')
            ->andWhere('d.legalCase = :case')
            ->setParameter('case', $case)
            ->orderBy('d.createdAt', 'DESC')
            ->getQuery()
            ->getResult();
    }

    /**
     * Documents auto-generate de aplicație (SOMATIE / CERERE_OP / OPIS). Split
     * față de `findSourceByCase()` clarifică UI „Documente generate" vs
     * „Documente sursă (uploadate)" în tab Documente (Pas 5.2).
     *
     * @return Document[]
     */
    public function findGeneratedByCase(LegalCase $case): array
    {
        return $this->findByCaseWithAutoGenerated($case, true);
    }

    /**
     * Documents uploadate de avocat ca anexe sursă (CONTRACT / FACTURA /
     * DOVADA_COMUNICARE / ANEXA / etc.). Exclude tipurile auto-generate.
     *
     * @return Document[]
     */
    public function findSourceByCase(LegalCase $case): array
    {
        return $this->findByCaseWithAutoGenerated($case, false);
    }

    /**
     * How many documents count against the per-case attachment cap: the evidence the
     * lawyer chose to annex, and nothing else.
     *
     * Two families are outside the count. The generated ones (SOMATIE / CERERE_OP /
     * OPIS) are produced by the platform, so charging them to the lawyer's quota would
     * shrink it without him uploading anything. The procedural ones
     * ({@see DocumentType::isProceduralRequirement()}) are imposed by the procedure and
     * gate the filing, so a case at the cap has to be able to attach them: otherwise a
     * product limit would leave a petition that can never be generated.
     */
    public function countCappedAttachments(LegalCase $case): int
    {
        $uncappedTypes = array_values(array_filter(
            DocumentType::cases(),
            static fn (DocumentType $type): bool => $type->isAutoGenerated() || $type->isProceduralRequirement(),
        ));

        return (int) $this->createQueryBuilder('d')
            ->select('COUNT(d.id)')
            ->andWhere('d.legalCase = :case')
            ->andWhere('d.documentType NOT IN (:types)')
            ->setParameter('case', $case)
            ->setParameter('types', $uncappedTypes)
            ->getQuery()
            ->getSingleScalarResult();
    }

    /**
     * @return Document[]
     */
    private function findByCaseWithAutoGenerated(LegalCase $case, bool $autoGenerated): array
    {
        $autoGeneratedTypes = array_values(array_filter(
            DocumentType::cases(),
            static fn (DocumentType $type): bool => $type->isAutoGenerated(),
        ));

        $qb = $this->createQueryBuilder('d')
            ->andWhere('d.legalCase = :case')
            ->setParameter('case', $case)
            ->orderBy('d.createdAt', 'DESC');

        if ($autoGenerated) {
            $qb->andWhere('d.documentType IN (:types)')->setParameter('types', $autoGeneratedTypes);
        } else {
            $qb->andWhere('d.documentType NOT IN (:types)')->setParameter('types', $autoGeneratedTypes);
        }

        return $qb->getQuery()->getResult();
    }

    /**
     * Bulk-attach pre-uploaded documents to a freshly persisted LegalCase.
     *
     * Used by the wizard step 4 submit: documents uploaded in step 0 are
     * persisted with `legalCase = NULL` (fallback path `_pending/{userId}/...`),
     * and only at submit are they linked to the case. Single UPDATE keeps the
     * transaction short — no per-row hydrate.
     *
     * @param int[] $documentIds
     */
    public function attachToCase(array $documentIds, LegalCase $case): int
    {
        if ($documentIds === []) {
            return 0;
        }

        return $this->createQueryBuilder('d')
            ->update()
            ->set('d.legalCase', ':case')
            // The draft is deleted with the submit, so the link goes with it.
            ->set('d.draft', ':noDraft')
            ->where('d.id IN (:ids)')
            ->setParameter('case', $case)
            ->setParameter('noDraft', null)
            ->setParameter('ids', $documentIds)
            ->getQuery()
            ->execute();
    }

    /**
     * Ids of the documents linked to the draft that its payload does not list,
     * so a list overwritten by a concurrent request can be repaired from the
     * link column.
     *
     * @param list<int> $knownIds
     * @return list<int>
     */
    public function findIdsByDraftNotIn(CaseDraft $draft, array $knownIds): array
    {
        $qb = $this->createQueryBuilder('d')
            ->select('d.id')
            ->andWhere('d.draft = :draft')
            ->setParameter('draft', $draft)
            ->orderBy('d.id', 'ASC');
        if ($knownIds !== []) {
            $qb->andWhere('d.id NOT IN (:known)')->setParameter('known', $knownIds);
        }

        return array_map(static fn (array $row): int => (int) $row['id'], $qb->getQuery()->getArrayResult());
    }

    /** @return list<Document> */
    public function findByDraft(CaseDraft $draft): array
    {
        return $this->createQueryBuilder('d')
            ->andWhere('d.draft = :draft')
            ->setParameter('draft', $draft)
            ->orderBy('d.id', 'ASC')
            ->getQuery()
            ->getResult();
    }

    /**
     * Uploads that belong to no case and no draft and are older than the cutoff.
     * A document still being read, or waiting for another attempt, is left out:
     * the worker would write on a deleted row.
     *
     * @return list<Document>
     */
    public function findOrphansOlderThan(\DateTimeImmutable $cutoff): array
    {
        return $this->createQueryBuilder('d')
            ->andWhere('d.legalCase IS NULL')
            ->andWhere('d.draft IS NULL')
            ->andWhere('d.createdAt < :cutoff')
            ->andWhere('d.extractionStatus NOT IN (:inFlight)')
            ->setParameter('cutoff', $cutoff)
            ->setParameter('inFlight', [ExtractionStatus::PROCESSING, ExtractionStatus::PENDING_RETRY])
            ->orderBy('d.id', 'ASC')
            ->getQuery()
            ->getResult();
    }
}
